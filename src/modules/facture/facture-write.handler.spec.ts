import { afterEach, describe, expect, it, jest } from '@jest/globals';
import { BaseWriteHandler } from 'src/core/ai-database/write/base-write-handler';
import { FactureWriteHandler } from './facture-write.handler';

/**
 * Numérotation des factures créées par l'IA : le numéro vient toujours de la
 * séquence du cabinet, jamais du plan (le LLM invente « F-{{today}}-001 »…).
 */
describe('FactureWriteHandler - numéro de facture', () => {
  const year = new Date().getFullYear();

  const createHandler = (lastNumero: string | null) => {
    const handler = Object.create(
      FactureWriteHandler.prototype,
    ) as FactureWriteHandler;
    const saved: any[] = [];
    const queryBuilder: any = {
      withDeleted: () => queryBuilder,
      where: () => queryBuilder,
      orderBy: () => queryBuilder,
      getOne: jest.fn(async () => (lastNumero ? { numero: lastNumero } : null)),
    };
    Object.assign(handler as object, {
      logger: { log: jest.fn(), warn: jest.fn(), debug: jest.fn() },
      filterKnownColumns: (fields: Record<string, any>) => ({ ...fields }),
      stripAutoGeneratedFields: (fields: Record<string, any>) => fields,
      dataSource: {
        getRepository: () => ({ findOne: jest.fn(async () => null) }),
      },
      factureRepo: {
        createQueryBuilder: () => queryBuilder,
        findOne: jest.fn(async () => null),
        save: jest.fn(async (facture: any) => {
          saved.push(facture);
          return { ...facture, id: 'facture-uuid-1' };
        }),
      },
    });
    return { handler, saved };
  };

  afterEach(() => {
    jest.restoreAllMocks();
  });

  it.each(['F-2026-10-18-001', '2026/001/01'])(
    'ignore le numéro "%s" proposé par le plan et suit la séquence',
    async (numero) => {
      const { handler, saved } = createHandler(`FAC-${year}-0041`);

      const result = await (handler as any).doInsert(
        { numero, dossier_id: 12, client_id: 7, montantHT: 100000 },
        'user-1',
      );

      expect(saved[0].numero).toBe(`FAC-${year}-0042`);
      expect(result.data.numero).toBe(`FAC-${year}-0042`);
      expect(result.message).toContain(`FAC-${year}-0042`);
    },
  );

  it('génère le premier numéro de la séquence sans facture existante', async () => {
    const { handler, saved } = createHandler(null);

    await (handler as any).doInsert(
      { dossier_id: 12, montantHT: 0 },
      'user-1',
    );

    expect(saved[0].numero).toBe(`FAC-${year}-0001`);
    expect(saved[0].libelle).toBe(`FAC-${year}-0001`);
  });

  it('retire le numéro des champs validés sans refuser la création', async () => {
    const { handler } = createHandler(null);

    const result = await handler.validateFields(
      { numero: 'F-{{today}}-001', dossier_id: 12, montantHT: 5000 },
      'INSERT',
    );

    expect(result.valid).toBe(true);
    expect(result.transformedFields).toEqual({
      dossier_id: 12,
      montantHT: 5000,
    });
  });

  it("n'annonce pas le numéro comme champ modifiable au planificateur", async () => {
    jest
      .spyOn(BaseWriteHandler.prototype, 'getWriteableFieldsSchema')
      .mockResolvedValue([
        { name: 'numero', label: 'Numéro', type: 'string', required: true },
        { name: 'montantHT', label: 'Montant HT', type: 'number' },
        { name: 'dossier_id', label: 'Dossier', type: 'reference' },
      ] as any);
    const { handler } = createHandler(null);

    const schema = await handler.getWriteableFieldsSchema();

    expect(schema.map((f) => f.name)).not.toContain('numero');
    expect(schema.map((f) => f.name)).toEqual(
      expect.arrayContaining(['montantHT', 'dossier_id']),
    );
  });
});
