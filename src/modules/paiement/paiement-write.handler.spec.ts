import { describe, expect, it, jest } from '@jest/globals';
import { PaiementWriteHandler } from './paiement-write.handler';
import { StatutPaiement } from './dto/create-paiement.dto';

/**
 * « 1000 FCFA reçus par virement sur @FAC-… » : `filterKnownColumns` renomme
 * `facture_id` en `facture` (propriété de la relation). La validation et
 * l'insertion lisaient seulement `factureId` / `facture_id` : tout paiement
 * planifié par l'IA était refusé (« La facture est requise »).
 */
describe('PaiementWriteHandler - facture du paiement', () => {
  const FACTURE = '6f1c2d3e-0000-4000-8000-000000000040';

  const createHandler = () => {
    const handler = Object.create(PaiementWriteHandler.prototype) as PaiementWriteHandler;
    const saved: any[] = [];
    Object.assign(handler as object, {
      logger: { log: jest.fn(), warn: jest.fn(), debug: jest.fn() },
      // Comme la vraie : `facture_id` (colonne) devient `facture` (propriété).
      filterKnownColumns: (fields: Record<string, any>) => {
        const { facture_id, ...rest } = fields;
        return facture_id !== undefined ? { ...rest, facture: facture_id } : { ...rest };
      },
      stripAutoGeneratedFields: (fields: Record<string, any>) => fields,
      factureRepo: {
        findOne: jest.fn(async () => ({ id: FACTURE, numero: 'FAC-2026-0040', montantTTC: 56667, paiements: [] })),
      },
      paiementRepo: {
        save: jest.fn(async (paiement: any) => {
          saved.push(paiement);
          return { ...paiement, id: 'paiement-1' };
        }),
      },
      updateFactureStatus: jest.fn(async () => undefined),
    });
    return { handler, saved };
  };

  it.each([
    ['facture', { facture: FACTURE }],
    ['facture objet', { facture: { id: FACTURE } }],
    ['facture_id', { facture_id: FACTURE }],
    ['factureId', { factureId: FACTURE }],
  ])('valide un paiement dont la facture arrive sous « %s »', async (_name, ref) => {
    const { handler } = createHandler();
    const result = await handler.validateFields({ ...ref, montant: 1000 }, 'INSERT');
    expect(result.errors).toEqual([]);
  });

  it('refuse toujours un paiement sans facture', async () => {
    const { handler } = createHandler();
    const result = await handler.validateFields({ montant: 1000 }, 'INSERT');
    expect(result.errors).toContain('La facture est requise (factureId ou facture)');
  });

  it('enregistre le paiement sur la facture renommée en `facture`', async () => {
    const { handler, saved } = createHandler();
    const result = await (handler as any).doInsert(
      { facture_id: FACTURE, montant: 1000, modePaiement: 0 },
      'user-1',
    );
    expect(result.success).toBe(true);
    expect(saved[0].factureId).toBe(FACTURE);
    expect(saved[0].montant).toBe(1000);
    expect(saved[0].status).toBe(StatutPaiement.VALIDE);
    expect((handler as any).updateFactureStatus).toHaveBeenCalledWith(FACTURE);
  });
});
