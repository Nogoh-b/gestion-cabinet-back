// src/modules/comptabilite/write/journal-write.handler.ts
import { Injectable, NotFoundException } from '@nestjs/common';
import { InjectRepository } from '@nestjs/typeorm';
import { DataSource, Repository } from 'typeorm';
import { JournalComptable } from '../entities/journal.entity';
import { TypeJournal } from '../enums/comptabilite.enums';
import { JOURNAUX_SYSCOHADA } from '../data/syscohada.data';
import { comparableKey } from 'src/core/ai-database/write/lenient-values';
import { BaseWriteHandler } from 'src/core/ai-database/write/base-write-handler';
import { SchemaMetadataService } from 'src/core/ai-database/schema-metadata.service';
import { EntityResolverService } from 'src/core/ai-database/write/entity-resolver.service';
import { WriteResult } from 'src/core/ai-database/write/write-handler.registry';
import {
  WriteableFieldSchema,
  ValidationResult,
} from 'src/core/ai-database/interface/entity-write-handler.interface';

/**
 * Handler custom pour les journaux comptables.
 * Logique métier :
 *   - un élément suffit (code, libellé ou type) : les autres sont déduits des
 *     journaux SYSCOHADA (ex: type BANQUE → code BNQ, « Journal banque »)
 *   - dédup par "code" (un journal ne peut exister 2x pour un même tenant)
 *   - actif par défaut : true
 */
@Injectable()
export class JournalWriteHandler extends BaseWriteHandler {
  constructor(
    dataSource: DataSource,
    schemaMetadata: SchemaMetadataService,
    entityResolver: EntityResolverService,
    @InjectRepository(JournalComptable)
    private readonly journalRepo: Repository<JournalComptable>,
  ) {
    super('journaux_comptables', dataSource, schemaMetadata, entityResolver);
  }

  async getWriteableFieldsSchema(): Promise<WriteableFieldSchema[]> {
    const fields = await super.getWriteableFieldsSchema();
    const enrichments: Record<string, Partial<WriteableFieldSchema>> = {
      code: {
        description: 'Code court du journal (déduit du type si absent)',
        example: 'VTE',
        required: false,
      },
      libelle: {
        description: 'Libellé du journal (déduit du type si absent)',
        example: 'Journal des ventes',
        required: false,
      },
      typeJournal: {
        description:
          'VENTES, ACHATS, CAISSE, BANQUE ou OD (déduit du code/libellé, OD par défaut)',
        required: false,
      },
      actif: { description: 'BD: 1=Actif (par défaut), 0=Inactif.' },
    };
    for (const f of fields) {
      if (enrichments[f.name]) Object.assign(f, enrichments[f.name]);
    }
    return fields;
  }

  async validateFields(
    fields: Record<string, any>,
    operation: 'INSERT' | 'UPDATE',
  ): Promise<ValidationResult> {
    const errors: string[] = [];
    const transformed = { ...fields };
    if (operation === 'INSERT') {
      const code = String(fields.code ?? '').trim();
      const libelle = String(fields.libelle ?? '').trim();
      if (!code && !libelle && !fields.typeJournal) {
        errors.push(
          'Précisez au moins le code, le libellé ou le type du journal (VENTES, ACHATS, CAISSE, BANQUE, OD)',
        );
      } else {
        // Les éléments manquants sont déduits des autres (journaux SYSCOHADA).
        const type =
          (fields.typeJournal as TypeJournal) ??
          this.inferType(`${code} ${libelle}`);
        const reference = JOURNAUX_SYSCOHADA.find(
          (j) => j.typeJournal === type,
        );
        transformed.typeJournal = type;
        transformed.libelle =
          libelle || reference?.libelle || `Journal ${code}`;
        if (code) transformed.code = code.slice(0, 10);
        else transformed.generatedCode = reference?.code ?? 'OD';
      }
    }
    return {
      valid: errors.length === 0,
      errors,
      transformedFields: transformed,
    };
  }

  private inferType(text: string): TypeJournal {
    const key = comparableKey(text);
    if (/vte|vente/.test(key)) return TypeJournal.VENTES;
    if (/ach/.test(key)) return TypeJournal.ACHATS;
    if (/cai|caisse/.test(key)) return TypeJournal.CAISSE;
    if (/bnq|banque/.test(key)) return TypeJournal.BANQUE;
    return TypeJournal.OD;
  }

  /** Code libre dérivé du code de référence : BNQ, BNQ2, BNQ3… */
  private async uniqueCode(base: string): Promise<string> {
    let code = base;
    for (let i = 2; i < 100; i++) {
      if (!(await this.journalRepo.findOne({ where: { code } }))) return code;
      code = `${base.slice(0, 8)}${i}`;
    }
    return code;
  }

  protected async doInsert(
    fields: Record<string, any>,
    userId: string,
  ): Promise<WriteResult> {
    // ⚠️ Pas de stripAutoGeneratedFields ici : "code" y figure (prudence
    // générique) alors que c'est la clé métier saisie du journal. Le retirer
    // faisait chercher le doublon avec code=undefined → le premier journal
    // existant était renvoyé au lieu d'en créer un.
    const safeFields = this.filterKnownColumns(fields);
    // Doublon : même code saisi, ou à défaut même libellé (« Journal banque »).
    const existing = safeFields.code
      ? await this.journalRepo.findOne({ where: { code: safeFields.code } })
      : await this.journalRepo.findOne({
          where: { libelle: safeFields.libelle },
        });
    if (!existing && !safeFields.code) {
      safeFields.code = await this.uniqueCode(
        String(fields.generatedCode ?? 'OD'),
      );
    }
    if (existing) {
      return {
        success: true,
        operation: 'INSERT',
        entityId: existing.id,
        affected: 0,
        data: existing,
        message: `Journal ${existing.code} déjà existant retourné (ID: ${existing.id}) — pas de doublon créé`,
      };
    }

    const data = {
      ...safeFields,
      actif:
        safeFields.actif !== undefined
          ? Boolean(Number(safeFields.actif))
          : true,
    };

    const record = this.journalRepo.create(data);
    const saved = (await this.journalRepo.save(
      record,
    )) as unknown as JournalComptable;

    return {
      success: true,
      operation: 'INSERT',
      entityId: saved.id,
      affected: 1,
      data: saved,
      message: `Journal "${saved.code} — ${saved.libelle}" créé`,
    };
  }

  protected async doUpdate(
    entityId: string | number,
    fields: Record<string, any>,
    userId: string,
  ): Promise<WriteResult> {
    const journal = await this.journalRepo.findOne({
      where: { id: entityId as any },
    });
    if (!journal)
      throw new NotFoundException(`Journal ${entityId} introuvable`);

    // Le code est une donnée saisie du journal : il reste modifiable.
    const safeFields = this.filterKnownColumns(fields);
    Object.assign(journal, safeFields);
    const saved = await this.journalRepo.save(journal);

    return {
      success: true,
      operation: 'UPDATE',
      entityId: saved.id,
      affected: 1,
      data: saved,
      message: `Journal "${saved.code}" mis à jour`,
    };
  }
}
