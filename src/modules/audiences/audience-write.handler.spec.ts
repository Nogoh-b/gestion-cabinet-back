import { BadRequestException } from '@nestjs/common';
import { AudienceWriteHandler } from './audience-write.handler';
import { AudienceStatus } from './entities/audience.entity';

const day = (offset: number) =>
  new Date(Date.now() + offset * 86_400_000).toISOString().slice(0, 10);

describe('AudienceWriteHandler : règles de date', () => {
  const repo = {
    create: jest.fn((value) => value),
    save: jest.fn(async (value) => ({ id: 7, ...value })),
    findOne: jest.fn(),
  };
  const getAccessProfile = jest.fn();
  let handler: any;

  beforeEach(() => {
    jest.clearAllMocks();
    getAccessProfile.mockResolvedValue({ isAdmin: true, permissions: new Map() });
    handler = Object.create(AudienceWriteHandler.prototype);
    Object.assign(handler, {
      audienceRepo: repo,
      permissions: { getAccessProfile },
      filterKnownColumns: (fields: Record<string, any>) => {
        const { late_scheduling_reason: _reason, ...rest } = fields;
        return rest;
      },
      stripAutoGeneratedFields: (fields: Record<string, any>) => fields,
    });
  });

  const insert = (fields: Record<string, any>) =>
    handler.doInsert({ dossier_id: 1, ...fields }, '3');

  it('refuse une audience programmée dans le passé', async () => {
    await expect(insert({ audience_date: day(-3) })).rejects.toThrow('strictement future');
    expect(repo.save).not.toHaveBeenCalled();
  });

  it('accepte une audience déjà tenue à une date passée', async () => {
    await expect(insert({ audience_date: day(-3), status: AudienceStatus.HELD })).resolves.toMatchObject({ success: true });
    expect(getAccessProfile).not.toHaveBeenCalled();
  });

  it('exige un motif sous 48 heures', async () => {
    await expect(insert({ audience_date: day(1), audience_time: '23:00' })).rejects.toThrow('10 caractères');
  });

  it('refuse sous 48 heures sans dérogation', async () => {
    getAccessProfile.mockResolvedValue({ isAdmin: false, permissions: new Map() });
    await expect(insert({ audience_date: day(1), audience_time: '23:00', late_scheduling_reason: 'Fixée par le greffe' })).rejects.toThrow(BadRequestException);
  });

  it('garde le motif dans les notes et pose l’instant UTC', async () => {
    await insert({ audience_date: day(1), audience_time: '23:00', late_scheduling_reason: 'Fixée par le greffe' });
    const saved = repo.save.mock.calls[0][0];
    expect(saved.notes).toContain('Fixée par le greffe');
    expect(saved.starts_at_utc).toBeInstanceOf(Date);
  });

  it('ne contrôle pas une modification qui garde le même horaire', async () => {
    repo.findOne.mockResolvedValue({
      id: 7,
      status: AudienceStatus.HELD,
      audience_date: day(-3),
      audience_time: '09:00:00',
      timezone: 'Africa/Ndjamena',
    });
    await expect(handler.doUpdate(7, { audience_date: day(-3), notes: 'Note' }, '3')).resolves.toMatchObject({ success: true });
    expect(getAccessProfile).not.toHaveBeenCalled();
  });

  it('contrôle une modification vers une date passée', async () => {
    repo.findOne.mockResolvedValue({
      id: 7,
      status: AudienceStatus.SCHEDULED,
      audience_date: day(10),
      audience_time: '09:00:00',
      timezone: 'Africa/Ndjamena',
    });
    await expect(handler.doUpdate(7, { audience_date: day(-3) }, '3')).rejects.toThrow('strictement future');
  });

  it('demande le motif dans la carte seulement quand il manque', () => {
    const op = { operation: 'INSERT', fields: { audience_date: day(1), audience_time: '23:00' } };
    expect(Object.keys(handler.requiredPlanFields(op))).toEqual(['late_scheduling_reason']);
    expect(handler.requiredPlanFields({ ...op, fields: { ...op.fields, late_scheduling_reason: 'Fixée par le greffe' } })).toEqual({});
    expect(handler.requiredPlanFields({ operation: 'INSERT', fields: { audience_date: day(10) } })).toEqual({});
  });
});
